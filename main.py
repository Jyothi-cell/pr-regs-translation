class HTMLToPDFConverter:  
    """  
    Converts textual HTML to a PDF document using PyMuPDF's Story API.  
    This class is designed to render the structured HTML generated by the AI model.  
    """  
    def __init__(self):  
        self.logger = logging.getLogger(__name__)  
        if not HTML_TO_PDF_AVAILABLE:  
            raise ImportError("PyMuPDF (fitz) is not available. Cannot create HTMLToPDFConverter.")
  
    def convert_html_to_pdf(self, html_path: str) -> bytes:  
        """  
        Converts an HTML file to a PDF using PyMuPDF's rendering engine.
  
        Args:  
            html_path: The file path to the HTML document.
  
        Returns:  
            The generated PDF content as bytes.  
        """  
        try:  
            with open(html_path, 'r', encoding='utf-8') as f:  
                html_content = f.read()
  
            self.logger.info("Converting text-based HTML to PDF using PyMuPDF Story API.")  
            pdf_bytes = self._render_html_with_story(html_content)
  
            if not pdf_bytes:  
                raise Exception("PDF generation with Story API produced no output.")
  
            self.logger.info(f"✓ PDF successfully generated from HTML: {len(pdf_bytes)} bytes")  
            return pdf_bytes
  
        except Exception as e:  
            error_msg = f"Error in HTML-to-PDF conversion: {str(e)}"  
            self.logger.error(error_msg)  
            # As a last resort, create a PDF with the error message  
            return self._create_error_pdf(error_msg)
  
    def _render_html_with_story(self, html_content: str) -> Optional[bytes]:  
        """  
        Renders HTML content to a PDF using the PyMuPDF Story and DocumentWriter API.  
        This method is suitable for structured, text-based HTML.
  
        Args:  
            html_content: The HTML content as a string.
  
        Returns:  
            The generated PDF as bytes, or None on failure.  
        """  
        temp_output_path = f"/tmp/story_output_{uuid.uuid4()}.pdf"  
        try:  
            # The Story API works best with content inside the <body> tag  
            if BS4_AVAILABLE:  
                soup = BeautifulSoup(html_content, 'html.parser')  
                body_content = soup.body.decode_contents() if soup.body else html_content  
            else:  
                body_content = html_content
  
            story = fitz.Story(html=body_content)  
            writer = fitz.DocumentWriter(temp_output_path)
              
            # Use a standard page size like 'letter'  
            page_rect = fitz.paper_rect("letter")  
            more = 1  
            while more:  
                device = writer.begin_page(page_rect)  
                more, _ = story.place(page_rect)  
                story.draw(device)  
                writer.end_page()
  
            writer.close()
  
            with open(temp_output_path, 'rb') as f:  
                pdf_bytes = f.read()
  
            self.logger.info(f"PyMuPDF Story API generated a PDF of {len(pdf_bytes)} bytes.")  
            return pdf_bytes
  
        except Exception as e:  
            self.logger.error(f"PyMuPDF Story API failed: {e}")  
            return None  
        finally:  
            if os.path.exists(temp_output_path):  
                os.remove(temp_output_path)
  
    def _create_error_pdf(self, error_message: str) -> bytes:  
        """  
        Creates a simple PDF document containing an error message.  
        This is a fallback for when the primary conversion fails.
  
        Args:  
            error_message: The error message to include in the PDF.
          
        Returns:  
            A PDF file as bytes.  
        """  
        try:  
            doc = fitz.open()  
            page = doc.new_page()  
            rect = page.rect + (50, 50, -50, -50)  
            page.insert_textbox(rect, f"PDF Generation Failed:\n\n{error_message}", fontsize=12, fontname="helv")  
            pdf_bytes = doc.tobytes()  
            doc.close()  
            return pdf_bytes  
        except Exception as e:  
            # If even this fails, we cannot proceed.  
            raise Exception(f"All PDF creation methods failed. Final error: {e}")
  
